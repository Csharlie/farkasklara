import type { ClientContent } from '../content'
import { createBuildContext } from './build-pages'
import { known } from './text'

/** PHP single-quoted string literal. */
function phpString(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function phpValue(value: unknown, indent: string): string {
  if (typeof value === 'string') return phpString(value)
  if (Array.isArray(value)) return `[${value.map((v) => phpValue(v, indent)).join(', ')}]`
  const inner = `${indent}    `
  const entries = Object.entries(value as Record<string, unknown>).map(([k, v]) => `${inner}${phpString(k)} => ${phpValue(v, inner)},`)
  return `[\n${entries.join('\n')}\n${indent}]`
}

/**
 * Settings of deploy/production/ajanlatkeres.php, generated from content so the
 * recipient, the domain and the service list have one source (company.ts,
 * services.ts, copy.ts). The recipient never comes from the request.
 *
 * `services` are the labels the quote form sends (fk-quote → service title).
 * `ipHashKey` is the HMAC-SHA256 key the rate limit uses to hash visitor IPs
 * (hash_hmac('sha256', $ip, $key) in ajanlatkeres.php/-cleanup.php) — a fresh
 * 128-bit secret on every build, never checked into the repo, and the
 * .htaccess denies direct access to the file that holds it.
 */
export function quoteFormConfig(content: ClientContent, ipHashKey: string) {
  const { company, copy } = content
  const email = known(company.email)
  const host = company.url ? new URL(company.url).hostname : undefined
  if (!email || !host) throw new Error('quote form: company.email and company.url must be real values')
  const errors = copy.quoteForm.errors
  return {
    to: email,
    from: email,
    host,
    site: company.name,
    phone: known(company.phone) ?? '',
    services: createBuildContext(content).services.map((s) => s.title),
    ipHashKey,
    messages: {
      name: errors.name,
      contact: errors.contact,
      email: errors.email,
      services: errors.services,
      consent: errors.consent,
      general: errors.general,
    },
  }
}

export function quoteFormConfigPhp(content: ClientContent, ipHashKey: string): string {
  return `<?php
// GENERATED by the fk-seo Vite plugin from src/content (src/data/quote-form-config.ts).
// Do not edit; not served directly (.htaccess denies it).
return ${phpValue(quoteFormConfig(content, ipHashKey), '')};
`
}
