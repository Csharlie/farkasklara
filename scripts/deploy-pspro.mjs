#!/usr/bin/env node
/**
 * Deploys the pspro.hu preview: https://pspro.hu/farkasklara/ behind a login gate.
 *
 *   pnpm deploy:pspro            build → stage → upload (FTP over TLS)
 *   pnpm deploy:pspro --dry-run  build → stage only, lists what would be uploaded
 *
 * Secrets come from .env.deploy.local (gitignored; template:
 * deploy/pspro/.env.deploy.example). The preview password is stored on the
 * server only as a PBKDF2 hash; the cookie-signing secret is regenerated on
 * every deploy (everyone logs in again). Credentials reach curl through
 * stdin, never through the command line.
 */
import { execSync, spawnSync } from 'node:child_process'
import { pbkdf2Sync, randomBytes } from 'node:crypto'
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const dryRun = process.argv.includes('--dry-run')

function readEnv(file) {
  const path = join(root, file)
  if (!existsSync(path)) return {}
  return Object.fromEntries(
    readFileSync(path, 'utf8')
      .split(/\r?\n/)
      .filter((line) => line.trim() && !line.trim().startsWith('#') && line.includes('='))
      .map((line) => {
        const i = line.indexOf('=')
        return [line.slice(0, i).trim(), line.slice(i + 1).trim().replace(/^(['"])(.*)\1$/, '$2')]
      }),
  )
}

function fail(message) {
  console.error(`\n✖ ${message}`)
  process.exit(1)
}

const base = readEnv('.env.pspro').DEPLOY_BASE
if (!base || !base.startsWith('/') || !base.endsWith('/')) fail('.env.pspro: DEPLOY_BASE must look like /farkasklara/')

const env = readEnv('.env.deploy.local')
const required = dryRun ? ['PREVIEW_USER', 'PREVIEW_PASSWORD'] : ['FTP_HOST', 'FTP_USER', 'FTP_PASS', 'FTP_DIR', 'PREVIEW_USER', 'PREVIEW_PASSWORD']
const missing = required.filter((key) => !env[key])
if (missing.length) fail(`.env.deploy.local is missing: ${missing.join(', ')} (template: deploy/pspro/.env.deploy.example)`)

// 1. Build ------------------------------------------------------------------
console.log(`▶ build (base ${base})`)
execSync('pnpm exec tsc -b && pnpm exec vite build --mode pspro --outDir dist-pspro --emptyOutDir', { cwd: root, stdio: 'inherit' })

// 2. Stage: build + gate files + generated config ----------------------------
const stage = join(root, '.deploy-stage')
rmSync(stage, { recursive: true, force: true })
mkdirSync(stage)
cpSync(join(root, 'dist-pspro'), stage, { recursive: true })
for (const file of ['gate.php', 'auth-check.php', 'login.php']) cpSync(join(root, 'deploy/pspro', file), join(stage, file))
writeFileSync(join(stage, '.htaccess'), readFileSync(join(root, 'deploy/pspro/.htaccess.tpl'), 'utf8').replaceAll('{{BASE}}', base))

const iterations = 210_000
const salt = randomBytes(16)
const hash = pbkdf2Sync(env.PREVIEW_PASSWORD, salt, iterations, 32, 'sha256')
const phpString = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
writeFileSync(
  join(stage, 'auth-config.php'),
  `<?php
// GENERATED by scripts/deploy-pspro.mjs — do not edit, do not commit.
return [
    'base' => ${phpString(base)},
    'user' => ${phpString(env.PREVIEW_USER)},
    'salt' => ${phpString(salt.toString('base64'))},
    'hash' => ${phpString(hash.toString('base64'))},
    'iterations' => ${iterations},
    'secret' => ${phpString(randomBytes(32).toString('hex'))},
    'ttl' => ${60 * 60 * 24 * 14},
];
`,
)

function listFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? listFiles(path) : [path]
  })
}

// Assets first, entry points last — the live site is never half-updated for long.
const entryLast = ['index.html', 'auth-config.php', 'gate.php', 'auth-check.php', 'login.php', '.htaccess']
const files = listFiles(stage)
  .map((path) => relative(stage, path).split(sep).join('/'))
  .sort((a, b) => entryLast.indexOf(a) - entryLast.indexOf(b) || a.localeCompare(b))

if (dryRun) {
  console.log(`\n✔ dry run — staged ${files.length} files in .deploy-stage (nothing uploaded):`)
  for (const file of files) console.log(`  ${file}`)
  process.exit(0)
}

// 3. Upload (FTP with mandatory TLS unless FTP_TLS=optional) -----------------
const remoteDir = `/${env.FTP_DIR.replace(/^\/+|\/+$/g, '')}/`
const tls = env.FTP_TLS === 'optional' ? '--ssl' : '--ssl-reqd'
console.log(`\n▶ upload ${files.length} files → ftp://${env.FTP_HOST}${remoteDir} (${tls})`)
const credentials = `user = "${env.FTP_USER.replace(/"/g, '\\"')}:${env.FTP_PASS.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"\n`
const curl = (args) => spawnSync('curl', ['--config', '-', tls, '--silent', '--show-error', ...args], { input: credentials, encoding: 'utf8' })

/** Remote size via FTP SIZE (curl -I) — null when unknown. */
function remoteSize(url) {
  const match = /Content-Length:\s*(\d+)/i.exec(curl(['-I', url]).stdout ?? '')
  return match ? Number(match[1]) : null
}

for (const file of files) {
  const url = `ftp://${env.FTP_HOST}${remoteDir}${file.split('/').map(encodeURIComponent).join('/')}`
  const localSize = statSync(join(stage, file)).size
  let error = ''
  for (let attempt = 1; attempt <= 3; attempt++) {
    const result = curl(['--ftp-create-dirs', '--fail', '-T', join(stage, file), url])
    if (result.status === 0) {
      error = ''
      break
    }
    error = result.stderr.trim()
    // Some servers answer 451 on the TLS data-channel close although the file
    // arrived intact — accept it when the remote size matches.
    if (remoteSize(url) === localSize) {
      error = ''
      break
    }
  }
  if (error) fail(`upload failed: ${file}\n${error}`)
  console.log(`  ✓ ${file}`)
}

rmSync(stage, { recursive: true, force: true })
console.log(`\n✔ deployed — https://pspro.hu${base}`)
